-- ==================== PROFILES POLICIES ====================
CREATE POLICY "profiles_select_public" ON profiles
  FOR SELECT
  TO anon, authenticated
  USING (true);

CREATE POLICY "profiles_update_own" ON profiles
  FOR UPDATE
  TO authenticated
  USING (auth.uid() = id);

