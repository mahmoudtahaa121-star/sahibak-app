-- ==================== PLACES POLICIES ====================
CREATE POLICY "places_select_public" ON places
  FOR SELECT
  TO anon, authenticated
  USING (
    status = 'approved'
    AND deleted_at IS NULL
    AND (provider_id IS NULL OR provider_id NOT IN (
      SELECT id FROM profiles WHERE is_banned = TRUE
    ))
  );

CREATE POLICY "places_select_provider_own" ON places
  FOR SELECT
  TO authenticated
  USING (auth.uid() = provider_id);

CREATE POLICY "places_insert_provider" ON places
  FOR INSERT
  TO authenticated
  WITH CHECK (auth.uid() = provider_id);

CREATE POLICY "places_update_provider_own" ON places
  FOR UPDATE
  TO authenticated
  USING (auth.uid() = provider_id);

