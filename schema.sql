-- ========================================
-- PROFILES TABLE
-- ========================================
CREATE TABLE IF NOT EXISTS profiles (
  id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
  full_name TEXT,
  phone TEXT,
  role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'provider', 'admin')),
  is_banned BOOLEAN NOT NULL DEFAULT FALSE,
  warning_count INT NOT NULL DEFAULT 0,
  ban_reason TEXT,
  banned_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS profiles_role_idx ON profiles(role);
CREATE INDEX IF NOT EXISTS profiles_banned_idx ON profiles(is_banned);

-- ========================================
-- CATEGORIES TABLE
-- ========================================
CREATE TABLE IF NOT EXISTS categories (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  parent_id INTEGER REFERENCES categories(id) ON DELETE SET NULL,
  name_ar TEXT NOT NULL,
  name_en TEXT,
  icon TEXT,
  color TEXT,
  sort_order INTEGER DEFAULT 0,
  is_active BOOLEAN DEFAULT TRUE,
  show_on_home BOOLEAN DEFAULT TRUE,
  place_type_hint TEXT CHECK (place_type_hint IN ('shop', 'person', 'both')),
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS categories_parent_id_idx ON categories(parent_id);
CREATE INDEX IF NOT EXISTS categories_is_active_idx ON categories(is_active);
CREATE INDEX IF NOT EXISTS categories_show_on_home_idx ON categories(show_on_home);
CREATE INDEX IF NOT EXISTS categories_sort_order_idx ON categories(sort_order);

-- ========================================
-- PLACES TABLE
-- ========================================
CREATE TABLE IF NOT EXISTS places (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  provider_id UUID REFERENCES profiles(id) ON DELETE SET NULL,
  area TEXT NOT NULL DEFAULT 'المنصورية',
  place_type TEXT NOT NULL DEFAULT 'shop' CHECK (place_type IN ('shop', 'person')),
  name_ar TEXT NOT NULL,
  name_en TEXT,
  description_ar TEXT,
  description_en TEXT,
  phone TEXT NOT NULL,
  whatsapp TEXT,
  address_text TEXT,
  latitude NUMERIC,
  longitude NUMERIC,
  image_url TEXT,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  admin_note TEXT,
  deleted_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS places_provider_idx ON places(provider_id);
CREATE INDEX IF NOT EXISTS places_area_idx ON places(area);
CREATE INDEX IF NOT EXISTS places_status_idx ON places(status);
CREATE INDEX IF NOT EXISTS places_type_idx ON places(place_type);
CREATE INDEX IF NOT EXISTS places_deleted_at_idx ON places(deleted_at);
CREATE INDEX IF NOT EXISTS places_created_at_idx ON places(created_at DESC);
CREATE INDEX IF NOT EXISTS places_updated_idx ON places(updated_at);

-- ========================================
-- PLACE_CATEGORIES JUNCTION TABLE
-- ========================================
CREATE TABLE IF NOT EXISTS place_categories (
  place_id UUID NOT NULL REFERENCES places(id) ON DELETE CASCADE,
  category_id INTEGER NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  PRIMARY KEY (place_id, category_id)
);

CREATE INDEX IF NOT EXISTS place_categories_category_id_idx ON place_categories(category_id);

-- ========================================
-- PLACE_SERVICES TABLE
-- ========================================
CREATE TABLE IF NOT EXISTS place_services (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  place_id UUID NOT NULL REFERENCES places(id) ON DELETE CASCADE,
  name_ar TEXT NOT NULL,
  description_ar TEXT,
  sort_order INTEGER DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS place_services_place_id_idx ON place_services(place_id);
CREATE INDEX IF NOT EXISTS place_services_sort_order_idx ON place_services(sort_order);

-- ========================================
-- PLACE_IMAGES TABLE (V2 ready)
-- ========================================
CREATE TABLE IF NOT EXISTS place_images (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  place_id UUID NOT NULL REFERENCES places(id) ON DELETE CASCADE,
  url TEXT NOT NULL,
  is_cover BOOLEAN NOT NULL DEFAULT FALSE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS place_images_place_idx ON place_images(place_id);

-- ========================================
-- PLACE_EDIT_REQUESTS TABLE
-- ========================================
CREATE TABLE IF NOT EXISTS place_edit_requests (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  place_id UUID NOT NULL REFERENCES places(id) ON DELETE CASCADE,
  provider_id UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  field_name TEXT NOT NULL,
  old_value TEXT,
  new_value TEXT,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  admin_note TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS edit_req_place_idx ON place_edit_requests(place_id);
CREATE INDEX IF NOT EXISTS edit_req_provider_idx ON place_edit_requests(provider_id);
CREATE INDEX IF NOT EXISTS edit_req_status_idx ON place_edit_requests(status);

-- ========================================
-- OFFERS TABLE
-- ========================================
CREATE TABLE IF NOT EXISTS offers (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  place_id UUID NOT NULL REFERENCES places(id) ON DELETE CASCADE,
  place_service_id UUID REFERENCES place_services(id) ON DELETE SET NULL,
  title_ar TEXT NOT NULL,
  description_ar TEXT,
  expires_at TIMESTAMPTZ,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  admin_note TEXT,
  deleted_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS offers_place_id_idx ON offers(place_id);
CREATE INDEX IF NOT EXISTS offers_place_service_id_idx ON offers(place_service_id);
CREATE INDEX IF NOT EXISTS offers_status_idx ON offers(status);
CREATE INDEX IF NOT EXISTS offers_expires_at_idx ON offers(expires_at);
CREATE INDEX IF NOT EXISTS offers_deleted_at_idx ON offers(deleted_at);
CREATE INDEX IF NOT EXISTS offers_created_at_idx ON offers(created_at DESC);
CREATE INDEX IF NOT EXISTS offers_updated_idx ON offers(updated_at);

-- ========================================
-- NEWS TABLE
-- ========================================
CREATE TABLE IF NOT EXISTS news (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  title_ar TEXT NOT NULL,
  body_ar TEXT,
  image_url TEXT,
  is_pinned BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
