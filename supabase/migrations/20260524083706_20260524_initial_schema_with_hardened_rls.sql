/*
  # Initial Schema — Sahibak Base Tables

  1. New Tables
    - `profiles` — user profiles with role (user/provider/admin), ban status
    - `categories` — hierarchical categories with parent_id self-reference
    - `places` — business/person listings with approval workflow
    - `place_categories` — junction table (place ↔ category)
    - `place_services` — services offered by a place
    - `place_images` — multiple images per place (V2)
    - `place_edit_requests` — provider edit requests needing admin approval
    - `offers` — time-limited offers on places/services
    - `news` — admin-posted news items
    - `favorites` — user favorite places
    - `likes` — user likes on places (V2)
    - `reports` — user reports on places
    - `device_tokens` — push notification tokens (V2)
    - `audit_log` — admin action audit trail
    - `app_config` — key-value configuration store

  2. Security
    - RLS enabled on all tables
    - Public read on approved, non-deleted places (excludes banned providers)
    - Provider INSERT/UPDATE on own places (status immutable for providers)
    - Admin-only UPDATE on places/offers status (approve/reject)
    - Admin-only INSERT/UPDATE/DELETE on categories and news
    - Admin-only UPDATE/DELETE on reports
    - Unique constraint on reports(user_id, place_id) prevents spam
    - Unique partial index on profiles.phone prevents duplicate accounts
    - pg_trgm GIN index on places.name_ar for efficient search

  3. Functions & Triggers
    - handle_new_user: auto-create profile on signup
    - touch_updated_at: auto-update updated_at on mutation
    - check_category_limit: enforce max categories per place type
    - check_provider_limits: enforce max places per provider from app_config

  4. Important Notes
    1) Providers CANNOT change the `status` field on their own places — only admins can approve/reject
    2) Same restriction applies to offers status
    3) Categories and news are fully admin-managed — no public write
    4) The reports unique constraint prevents a user from reporting the same place twice
*/

